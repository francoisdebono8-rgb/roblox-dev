#!/usr/bin/env python3
"""Step 10-11 of SyphoDev's animation video, for Ninja Duel: does Roblox pose every body part
exactly where the Blender render put it, and does the clip last exactly its authored length?

    # 1. write the Luau proof for one clip (run it on the SERVER of a Play session, Studio MCP)
    python3 studio_parity.py luau rig.json clips.json <clip name> [frames...] > proof.luau
    # 2. compare what Studio returned with the render's posed parts
    python3 studio_parity.py check rig.json clips.json <clip name> studio.json [resolved.json]

The Luau builds a real fighter with the game's own constructor (Server/World.rig), feeds the
clip to the game's own decoder and sampler (Client/AuthoredMotion), writes every
Motor6D.Transform before the physics step, and reads every part back relative to the root.
The check recomputes the same parts down the Motor6D chain of rig.json:
  * from the exported rows (what the game receives): Roblox must agree to < 1e-4 stud;
  * from resolved.json (what r6_clip.py rendered, unrounded): the gap is the export rounding
    of AuthoredClips (4 decimals per quaternion component), reported, not hidden.
"""
import json
import math
import sys

FPS = 30


def qmat(q):
    x, y, z, w = q
    n = math.sqrt(x * x + y * y + z * z + w * w)
    x, y, z, w = x / n, y / n, z / n, w / n
    return [[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
            [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
            [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]]


def mm(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def mv(a, v):
    return [sum(a[i][k] * v[k] for k in range(3)) for i in range(3)]


def compose(A, B):  # (R, p) * (R, p)
    return (mm(A[0], B[0]), [x + y for x, y in zip(mv(A[0], B[1]), A[1])])


def inv(A):
    Rt = [list(r) for r in zip(*A[0])]
    return (Rt, [-x for x in mv(Rt, A[1])])


ID = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]


def parts_from(rig, T):
    """T: motor name -> (R, p). Every part's centre relative to the root, down the chain."""
    W = {"HumanoidRootPart": (ID, [0.0, 0.0, 0.0])}
    pending = list(rig["joints"])
    while pending:
        for j in list(pending):
            if j["part0"] in W:
                c0 = (j["c0"]["rows"], j["c0"]["pos"])
                c1 = (j["c1"]["rows"], j["c1"]["pos"])
                W[j["part1"]] = compose(compose(compose(W[j["part0"]], c0), T.get(j["name"], (ID, [0, 0, 0]))), inv(c1))
                pending.remove(j)
                break
    return {p: W[p][1] for p in W if p != "HumanoidRootPart"}


def transforms_from_rows(rig, clip, f):
    keys = {v: k for k, v in rig["clip_keys"].items()}
    T = {}
    for jk, rows in clip["joints"].items():
        r = rows[f]
        if jk == "Root":
            T[keys[jk]] = (qmat(r[3:7]), r[0:3])
        else:
            T[keys[jk]] = (qmat(r), [0.0, 0.0, 0.0])
    return T


def luau(rig, clips, name, frames):
    clip = clips[name]
    flat = {j: [v for row in rows for v in row] for j, rows in clip["joints"].items()}
    joints = ",".join(f'{j}={{{",".join(repr(v) for v in vals)}}}' for j, vals in flat.items())
    markers = ",".join(f"{k}={v}" for k, v in clip["markers"].items())
    motor = ",".join(f'{v}="{k}"' for k, v in rig["clip_keys"].items())
    body = ",".join(f"{p}=true" for p in rig["sizes"])
    return f'''-- GENERATED by tools/syphodev/studio_parity.py: SyphoDev step 10-11 for "{name}" (SERVER, Play).
local RS=game:GetService("RunService")
local World=require(game.ServerScriptService:FindFirstChild("World",true))
local Fighters=require(game.ReplicatedStorage:FindFirstChild("Fighters",true))
local AM=require(game:GetService("StarterPlayer"):FindFirstChild("AuthoredMotion",true))
AM.data["{name}"]={{fps={clip["fps"]},frames={clip["frames"]},length={clip["length"]},loop={str(clip["loop"]).lower()},markers={{{markers}}},meta={{}},joints={{{joints}}}}}
local MOTOR={{{motor}}}
local BODY={{{body}}}  -- the rig's parts only (costume pieces are welded on, not posed)
local old=workspace:FindFirstChild("SyphoProof") if old then old:Destroy() end
local folder=Instance.new("Folder") folder.Name="SyphoProof" folder.Parent=workspace
local model=World.rig(folder,Fighters.Lion,CFrame.new(0,400,0),"SyphoProof")
if model.Parent==nil then model.Parent=folder end
model.HumanoidRootPart.Anchored=true
local motors={{}}
for _,m in model:GetDescendants() do if m:IsA("Motor6D") then motors[m.Name]=m end end
local out={{length=AM.length("{name}"),fps=AM.clip("{name}").fps,frames={{}}}}
for _,f in {{{",".join(str(f) for f in frames)}}} do
	local pose=AM.sample("{name}",f/{clip["fps"]})
	local conn=RS.PreSimulation:Connect(function()
		for j,cf in pose do motors[MOTOR[j]].Transform=cf end
	end)
	RS.Heartbeat:Wait() RS.Heartbeat:Wait() RS.Heartbeat:Wait()
	conn:Disconnect()
	local root=model.HumanoidRootPart.CFrame
	local parts={{}}
	for _,p in model:GetChildren() do
		if p:IsA("BasePart") and BODY[p.Name] then
			local c=root:ToObjectSpace(p.CFrame) parts[p.Name]={{math.round(c.X*1e6)/1e6,math.round(c.Y*1e6)/1e6,math.round(c.Z*1e6)/1e6}}
		end
	end
	out.frames[tostring(f)]=parts
end
return game:GetService("HttpService"):JSONEncode(out)
'''


def check(rig, clips, name, studio, resolved=None):
    clip = clips[name]
    want_len = round((clip["frames"] - 1) / clip["fps"], 4) if not clip["loop"] else clip["length"]
    ok = True
    print(f"length: Studio {studio['length']} s, authored {clip['length']} s")
    if abs(studio["length"] - clip["length"]) > 1e-6 or abs(want_len - clip["length"]) > 1e-3:
        ok = False
        print("  FAIL length")
    worst_rows = worst_render = 0.0
    for fs, parts in studio["frames"].items():
        f = int(fs)
        exp = parts_from(rig, transforms_from_rows(rig, clip, f))
        for p, xyz in parts.items():
            if p not in exp:
                continue  # costume pieces (hair, sash, eyes) are not on rig.json
            worst_rows = max(worst_rows, math.dist(xyz, exp[p]))
        if resolved:
            t = f / clip["fps"]
            for k in resolved["keys"]:
                if abs(k["t"] - t) < 1e-3:
                    T = {j: (v["rows"], v["pos"]) for j, v in k["poses"].items()}
                    ren = parts_from(rig, T)
                    for p, xyz in parts.items():
                        if p in ren:
                            worst_render = max(worst_render, math.dist(xyz, ren[p]))
    print(f"parts vs the exported rows (engine parity): worst {worst_rows:.6f} stud over {len(studio['frames'])} frames")
    if worst_rows > 1e-4:
        ok = False
        print("  FAIL engine parity > 1e-4 stud")
    if resolved:
        print(f"parts vs the unrounded render at the keys (export rounding): worst {worst_render:.6f} stud")
    print("PASS" if ok else "FAIL")
    return ok


if __name__ == "__main__":
    mode, rig_p, clips_p, name = sys.argv[1:5]
    rig, clips = json.load(open(rig_p)), json.load(open(clips_p))
    if mode == "luau":
        frames = [int(x) for x in sys.argv[5:]] or list(range(clips[name]["frames"]))
        print(luau(rig, clips, name, frames))
    else:
        studio = json.load(open(sys.argv[5]))
        resolved = json.load(open(sys.argv[6])) if len(sys.argv) > 6 else None
        sys.exit(0 if check(rig, clips, name, studio, resolved) else 1)
