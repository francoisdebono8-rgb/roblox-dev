# Writes src/Server/ArenaMeshData.luau from the Studio import of
# tools/blender/arena_assets.py:
#   imports/arena/Arena_Assets.studio.json : name, mesh id, size, centre
#     (the centres in arena-asset space, from the Blender bounding boxes);
#   imports/arena/Arena_Assets.manifest.json : asset (body), colour, material.
# Every asset is modelled at its own origin, so a piece's offset is its centre.
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
IMP = os.path.join(HERE, "imports", "arena")
def f(v): return ("%.4f" % v).rstrip("0").rstrip(".") or "0"
man = json.load(open(os.path.join(IMP, "Arena_Assets.manifest.json")))["pieces"]
pieces = json.load(open(os.path.join(IMP, "Arena_Assets.studio.json")))
assets = {}
for p in pieces:
    m = man.get(p["name"])
    if not m:
        print("no manifest entry for", p["name"]); continue
    assets.setdefault(m["body"], []).append((p, m))
out = ["-- Generated by tools/blender/arena_to_luau.py from the Studio import of",
       "-- tools/blender/arena_assets.py. Do not edit by hand: re-run the script.", "return {"]
for asset in sorted(assets):
    out.append("\t[%s]={" % json.dumps(asset))
    for p, m in sorted(assets[asset], key=lambda x: x[0]["name"]):
        c = m["color"]
        piece = p["name"].split("__", 1)[1]
        out.append('\t\t{name=%s,mesh=%s,offset=Vector3.new(%s,%s,%s),size=Vector3.new(%s,%s,%s),color=Color3.fromRGB(%d,%d,%d),material=%s},' % (
            json.dumps(piece), json.dumps(p["mesh"]), f(p["pos"][0]), f(p["pos"][1]), f(p["pos"][2]),
            f(p["size"][0]), f(p["size"][1]), f(p["size"][2]), c[0], c[1], c[2], json.dumps(m.get("material", "SmoothPlastic"))))
    out.append("\t},")
out.append("}")
open(os.path.join(ROOT, "src", "Server", "ArenaMeshData.luau"), "w").write("\n".join(out) + "\n")
print("wrote", len(out), "lines,", len(assets), "assets")
