"""A look of the eight's pipeline (look_<name>.py, nd_look / nd_kit) drawn on the client, with
nothing to upload (27/11, passe 3: the Ōtsutsuki, « comme un vrai perso »).

The eight are uploaded through Studio's 3D importer (looks_to_luau.py, Server/LookMeshData).
This writes the same pieces as packed EditableMesh data (Client/MeshKit's format), each on its
body part at its rest-pose offset, coloured by the manifest:

    python3 look_to_client.py look_otsutsuki.py Look_Otsutsuki ../../src/Client/BossMeshData.luau

Client/BossFX puts them on the body (body.CFrame * offset, the rig's own sizes: the duel's rig
is the one the look is modelled on, so nothing is rescaled)."""
import math
import os
import runpy
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.environ.setdefault("ND_OUT", "/tmp")


def main(script, stem, dst):
    import nd_look
    import nd_look as L
    L.preview = lambda *a, **k: None          # no renders here
    runpy.run_path(os.path.join(HERE, script), run_name="__look__")
    import bpy
    from mathutils import Vector
    from nd_mesh import Piece, piece_luau
    rows = []
    tris = 0
    for ob in sorted(bpy.data.objects, key=lambda o: o.name):
        if ob.type != "MESH" or ob.name not in nd_look.MANIFEST:
            continue
        m = nd_look.MANIFEST[ob.name]
        body, rgb = m["body"], m["color"]
        rest = Vector(nd_look.REST[body])
        dg = bpy.context.evaluated_depsgraph_get()
        me = ob.evaluated_get(dg).to_mesh()
        me.calc_loop_triangles()
        mw = ob.matrix_world
        pc = Piece(ob.name, m.get("material", "SmoothPlastic"), flat=False, reflect=m.get("reflectance", 0))
        base = [c / 255 for c in rgb]
        for v in me.vertices:
            b = mw @ v.co
            r = Vector((-b.x, b.z, b.y)) - rest          # Roblox frame, body space
            n = (mw.to_3x3() @ v.normal)
            ny = n.z                                     # Roblox up
            k = .86 + .14 * max(-1, min(1, ny))          # a light from above
            pc.add(Vector((r.x, -r.z, r.y)), tuple(c * k for c in base))   # nd_mesh's frame
        for t in me.loop_triangles:
            pc.face(*t.vertices)
        ob.evaluated_get(dg).to_mesh_clear()
        tris += len(pc.f)
        spec = piece_luau(pc)
        rows.append("\t{on=%s,%s" % ('"%s"' % body, spec[1:]))
    # (a module's source must stay under 200 000 characters: the pieces go in chunks)
    gen = "-- Generated by tools/blender/look_to_client.py from tools/blender/%s. Do not edit: re-run the script." % script
    base = os.path.splitext(dst)[0]
    name = os.path.basename(base)
    for old in [f for f in os.listdir(os.path.dirname(dst) or ".") if f.startswith(name) and f[len(name):-5].isdigit()]:
        os.remove(os.path.join(os.path.dirname(dst), old))
    chunks, cur, size = [], [], 0
    for r in rows:
        if cur and size + len(r) > 150000:
            chunks.append(cur); cur, size = [], 0
        cur.append(r); size += len(r)
    if cur:
        chunks.append(cur)
    names = []
    for i, ch in enumerate(chunks, 1):
        names.append("%s%d" % (name, i))
        with open("%s%d.luau" % (base, i), "w") as f:
            f.write(gen + "\nreturn {\n" + ",\n".join(ch) + "\n}\n")
    with open(dst, "w") as f:
        f.write(gen + "\n-- {look = {{on=body part, name, mat, o (offset from the part's rest centre), h, n, m, d}, ...}}\n"
                "local list={}\nfor _,name in {%s} do\n\tfor _,spec in require(script.Parent[name]) do table.insert(list,spec) end\nend\n"
                "return {[%s]=list}\n" % (",".join('"%s"' % n for n in names), '"%s"' % stem))
    print("wrote", dst, len(rows), "pieces", tris, "tris")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
