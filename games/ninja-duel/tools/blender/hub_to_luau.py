"""Writes src/Client/HubMeshAssets.luau from the Studio import of hub_fbx.py:
imports/hub/Hub.studio.json ([{name: "<Model>__<Piece>", mesh: "rbxassetid://...",
size: [x,y,z]}], printed by hub_studio_dump.luau) checked against
imports/hub/Hub.manifest.json. Do not edit the output: re-run the script."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
IMP = os.path.join(HERE, "imports", "hub")
man = json.load(open(os.path.join(IMP, "Hub.manifest.json")))["pieces"]
studio = json.load(open(os.path.join(IMP, "Hub.studio.json")))
models = {}
for p in studio:
    m = man.get(p["name"])
    if not m:
        print("not in the manifest:", p["name"]); continue
    models.setdefault(m["model"], {})[m["piece"]] = p["mesh"]
missing = sorted(set(man) - {p["name"] for p in studio})
out = ["-- Generated by tools/blender/hub_to_luau.py from the Studio import of",
       "-- tools/blender/hub_fbx.py. Konoha's pieces published as meshes: Client/MeshKit",
       "-- loads these by id instead of building them on the player's computer.", "return {"]
for model in sorted(models):
    out.append("\t[%s]={%s}," % (json.dumps(model), ",".join("[%s]=%s" % (json.dumps(k), json.dumps(v)) for k, v in sorted(models[model].items()))))
out.append("}")
open(os.path.join(ROOT, "src", "Client", "HubMeshAssets.luau"), "w").write("\n".join(out) + "\n")
print("wrote", sum(len(v) for v in models.values()), "pieces;", len(missing), "not imported yet", missing[:8])
