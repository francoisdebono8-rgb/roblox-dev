# Writes src/Server/LookMeshData.luau from what Studio imported
# (imports/<Look>.studio.json: name, mesh id, size, position from the model
# pivot = the rig root at rest) and the Blender manifest
# (imports/<Look>.manifest.json: body part, colour, material).
import json, os, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
REST = {
    "LowerTorso": (0, 0, 0), "UpperTorso": (0, 1.15, 0), "Head": (0, 2.75, 0),
    "LeftUpperArm": (-1.24, 1.1, 0), "RightUpperArm": (1.24, 1.1, 0), "LeftLowerArm": (-1.24, .1, 0), "RightLowerArm": (1.24, .1, 0),
    "LeftHand": (-1.24, -.63, 0), "RightHand": (1.24, -.63, 0), "LeftUpperLeg": (-.5, -1.05, 0), "RightUpperLeg": (.5, -1.05, 0),
    "LeftLowerLeg": (-.5, -2.1, 0), "RightLowerLeg": (.5, -2.1, 0), "LeftFoot": (-.5, -2.8, -.15), "RightFoot": (.5, -2.8, -.15),
}
FIGHTER = {"Look_Naruto": "Naruto", "Look_Sasuke": "Sasuke", "Look_Gaara": "Gaara", "Look_Lee": "Rock Lee", "Look_Neji": "Neji",
           "Look_Itachi": "Itachi", "Look_Minato": "Minato", "Look_Kakashi": "Kakashi"}
HIDE = ["Head", "UpperTorso", "LowerTorso", "LeftUpperArm", "RightUpperArm", "LeftLowerArm", "RightLowerArm", "LeftHand", "RightHand",
        "LeftUpperLeg", "RightUpperLeg", "LeftLowerLeg", "RightLowerLeg", "LeftFoot", "RightFoot"]
def f(v): return ("%.4f" % v).rstrip("0").rstrip(".") or "0"
out = ["-- Generated by tools/blender/looks_to_luau.py from the Studio imports of",
       "-- tools/blender/look_*.py. Do not edit by hand: re-run the script.", "return {"]
for studio in sorted(glob.glob(os.path.join(HERE, "imports", "*.studio.json"))):
    stem = os.path.basename(studio)[:-len(".studio.json")]
    man = json.load(open(os.path.join(HERE, "imports", stem + ".manifest.json")))["pieces"]
    pieces = json.load(open(studio))
    out.append('\t[%s]={hide={%s},pieces={' % (json.dumps(FIGHTER[stem]), ",".join(json.dumps(h) for h in HIDE)))
    for p in pieces:
        base = p["name"].split(".")[0]
        m = man.get(base)
        if not m:
            print("no manifest entry for", p["name"]); continue
        body = m["body"]; r = REST[body]
        off = [p["pos"][i] - r[i] for i in range(3)]
        c = m["color"]
        out.append('\t\t{name=%s,body=%s,mesh=%s,offset=Vector3.new(%s,%s,%s),size=Vector3.new(%s,%s,%s),color=Color3.fromRGB(%d,%d,%d),material=%s,reflectance=%s},' % (
            json.dumps(p["name"]), json.dumps(body), json.dumps(p["mesh"]), f(off[0]), f(off[1]), f(off[2]),
            f(p["size"][0]), f(p["size"][1]), f(p["size"][2]), c[0], c[1], c[2], json.dumps(m.get("material", "SmoothPlastic")), f(m.get("reflectance", 0))))
    out.append("\t}},")
out.append("}")
open(os.path.join(ROOT, "src", "Server", "LookMeshData.luau"), "w").write("\n".join(out) + "\n")
print("wrote", len(out), "lines")
